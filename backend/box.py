"""
SQLite storage for trainer boxes (Caja de Bill, #73).

Each trainer (a ``trainer_id`` generated by the browser) owns one box: the
Pokémon they asked Bill to keep. It lives in the same SQLite file as the query
log (``DB_PATH``) but in its own module and tables, so it can move out with Bill
when he becomes a separate service.

- One row per species or form, keyed by the name of its Pokédex entry. The row
  keeps a copy of the entry's static data (types, base stats, defense), so most
  questions about a box need no further MCP call.
- A box holds at most ``MAX_POKEMON``. The check and the insert run in one
  ``BEGIN IMMEDIATE`` transaction: the conversation lock is per conversation, not
  per trainer, so two requests of one trainer can write at the same time.
- A box nobody touched for ``TTL_DAYS`` is deleted by ``purge_inactive``.
- Times are epoch seconds.
- One connection per call, closed when done. The schema is created on first use.
- The ``trainer_id`` is the only credential of a box: no function returns it and
  no error message carries it.
"""

import asyncio
import json
import logging
import os
import sqlite3
import time
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterator

logger = logging.getLogger(__name__)

DB_PATH = os.environ.get("DB_PATH", "data/queries.db")
BUSY_TIMEOUT_SECONDS = 5.0


def _env_int(name: str, default: int) -> int:
    try:
        value = int(os.environ.get(name) or default)
    except ValueError:
        value = 0
    if value < 1:
        logger.warning("[BOX] %s inválido, usando %d", name, default)
        return default
    return value


MAX_POKEMON = _env_int("BOX_MAX_POKEMON", 30)
TTL_DAYS = _env_int("BOX_TTL_DAYS", 90)

_SCHEMA = """
CREATE TABLE IF NOT EXISTS box_trainers (
  trainer_id TEXT PRIMARY KEY, created_at INTEGER NOT NULL, last_seen INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS box_pokemon (
  trainer_id TEXT NOT NULL, pokemon TEXT NOT NULL,
  pokemon_id INTEGER NOT NULL, types TEXT NOT NULL,
  base_stats TEXT NOT NULL, defense TEXT,
  added_at INTEGER NOT NULL,
  PRIMARY KEY (trainer_id, pokemon));
"""


@dataclass(frozen=True)
class Entry:
    """What a box keeps of a Pokédex entry."""

    name: str  # the entry's name: "pikachu", "giratina-altered"
    pokemon_id: int
    types: list[str]
    base_stats: dict[str, int]
    defense: dict[str, Any] | None = None


@contextmanager
def _connect() -> Iterator[sqlite3.Connection]:
    Path(DB_PATH).parent.mkdir(parents=True, exist_ok=True)
    # Autocommit: transactions are opened explicitly (BEGIN IMMEDIATE) where they matter.
    conn = sqlite3.connect(DB_PATH, timeout=BUSY_TIMEOUT_SECONDS, isolation_level=None)
    try:
        conn.executescript(_SCHEMA)
        yield conn
    finally:
        conn.close()


@contextmanager
def _write(conn: sqlite3.Connection) -> Iterator[None]:
    """A write transaction that takes the lock up front, so a count read inside it stays true."""
    conn.execute("BEGIN IMMEDIATE")
    try:
        yield
    except BaseException:
        conn.execute("ROLLBACK")
        raise
    conn.execute("COMMIT")


def _count(conn: sqlite3.Connection, trainer_id: str) -> int:
    return conn.execute("SELECT COUNT(*) FROM box_pokemon WHERE trainer_id = ?", (trainer_id,)).fetchone()[0]


def _touch(conn: sqlite3.Connection, trainer_id: str, now: int) -> None:
    conn.execute("UPDATE box_trainers SET last_seen = ? WHERE trainer_id = ?", (now, trainer_id))


def store(trainer_id: str, entries: list[Entry], *, now: int | None = None) -> dict[str, Any]:
    """Put ``entries`` in the trainer's box, in order, until it is full.

    Returns the names ``stored``, the ones ``already`` there and the ones left out because
    the box was ``full``, plus the box's ``count`` and ``capacity``. The trainer's row is
    created by their first stored Pokémon.
    """
    now = int(time.time()) if now is None else now
    stored: list[str] = []
    already: list[str] = []
    full: list[str] = []
    with _connect() as conn, _write(conn):
        have = {row[0] for row in conn.execute("SELECT pokemon FROM box_pokemon WHERE trainer_id = ?", (trainer_id,))}
        for entry in entries:
            if entry.name in have:
                if entry.name not in already and entry.name not in stored:
                    already.append(entry.name)
            elif len(have) >= MAX_POKEMON:
                if entry.name not in full:
                    full.append(entry.name)
            else:
                conn.execute(
                    "INSERT INTO box_pokemon (trainer_id, pokemon, pokemon_id, types, base_stats, defense, added_at) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (
                        trainer_id,
                        entry.name,
                        entry.pokemon_id,
                        json.dumps(entry.types, ensure_ascii=False),
                        json.dumps(entry.base_stats, ensure_ascii=False),
                        json.dumps(entry.defense, ensure_ascii=False) if entry.defense is not None else None,
                        now,
                    ),
                )
                have.add(entry.name)
                stored.append(entry.name)
        if stored:
            conn.execute(
                "INSERT INTO box_trainers (trainer_id, created_at, last_seen) VALUES (?, ?, ?) "
                "ON CONFLICT(trainer_id) DO UPDATE SET last_seen = excluded.last_seen",
                (trainer_id, now, now),
            )
        else:
            _touch(conn, trainer_id, now)
        count = len(have)
    return {"stored": stored, "already": already, "full": full, "count": count, "capacity": MAX_POKEMON}


def release(trainer_id: str, names: list[str], *, now: int | None = None) -> dict[str, Any]:
    """Take the Pokémon named ``names`` (entry names) out of the trainer's box.

    Returns the names ``released`` and the ones ``not_in_box``, plus ``count`` and ``capacity``.
    """
    now = int(time.time()) if now is None else now
    released: list[str] = []
    not_in_box: list[str] = []
    with _connect() as conn, _write(conn):
        for name in dict.fromkeys(names):
            cursor = conn.execute("DELETE FROM box_pokemon WHERE trainer_id = ? AND pokemon = ?", (trainer_id, name))
            (released if cursor.rowcount else not_in_box).append(name)
        _touch(conn, trainer_id, now)
        count = _count(conn, trainer_id)
    return {"released": released, "not_in_box": not_in_box, "count": count, "capacity": MAX_POKEMON}


def list_box(trainer_id: str, *, now: int | None = None) -> dict[str, Any]:
    """The trainer's box, oldest first: ``count``, ``capacity`` and each Pokémon's stored data."""
    now = int(time.time()) if now is None else now
    with _connect() as conn:
        rows = conn.execute(
            "SELECT pokemon, pokemon_id, types, base_stats, defense FROM box_pokemon "
            "WHERE trainer_id = ? ORDER BY added_at, rowid",
            (trainer_id,),
        ).fetchall()
        _touch(conn, trainer_id, now)
    pokemon = [
        {
            "name": name,
            "id": pokemon_id,
            "types": json.loads(types),
            "base_stats": json.loads(base_stats),
            "defense": json.loads(defense) if defense else None,
        }
        for name, pokemon_id, types, base_stats, defense in rows
    ]
    return {"count": len(pokemon), "capacity": MAX_POKEMON, "pokemon": pokemon}


def purge_inactive(days: int | None = None, *, now: int | None = None) -> int:
    """Delete the boxes nobody touched in ``days`` (default ``TTL_DAYS``). Returns how many.

    0 when the database file does not exist yet: purging never creates it.
    """
    if not Path(DB_PATH).is_file():
        return 0
    now = int(time.time()) if now is None else now
    cutoff = now - (TTL_DAYS if days is None else days) * 86_400
    with _connect() as conn, _write(conn):
        conn.execute(
            "DELETE FROM box_pokemon WHERE trainer_id IN (SELECT trainer_id FROM box_trainers WHERE last_seen < ?)",
            (cutoff,),
        )
        removed = conn.execute("DELETE FROM box_trainers WHERE last_seen < ?", (cutoff,)).rowcount
    if removed:
        logger.info("[BOX] %d cajas inactivas eliminadas", removed)
    return removed


async def purge_periodically(interval_seconds: int = 3600) -> None:
    """Purge inactive boxes now and every ``interval_seconds`` (started in ``main.lifespan``)."""
    while True:
        try:
            await asyncio.to_thread(purge_inactive)
        except Exception:
            logger.exception("[BOX] Error purgando cajas inactivas")
        await asyncio.sleep(interval_seconds)
